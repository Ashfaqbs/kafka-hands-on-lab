package com.example.kafkareference.dto;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

import java.time.Instant;
import java.util.UUID;

/**
 * Incoming message from the Python producer on topic orders.raw.
 *
 * record — Java 17 feature. Generates a final, immutable class with:
 *   - A canonical constructor (all fields)
 *   - Accessor methods (orderId(), customerId(), etc. — no get prefix)
 *   - equals(), hashCode(), toString() based on all fields
 *   Records are ideal for DTOs: they carry data, have no mutable state,
 *   and require zero boilerplate.
 *
 * @JsonIgnoreProperties(ignoreUnknown = true) — Jackson annotation.
 *   If the Python producer adds a new field (e.g. "region") in the future,
 *   deserialization will NOT fail — the extra field is silently ignored.
 *   Without this, an unknown field would throw UnrecognizedPropertyException,
 *   which routes the message to the DLT as a deserialization failure.
 *   This is the safe default for consumer DTOs — allow producers to evolve
 *   their schema without breaking existing consumers.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public record RawOrderEvent(
    UUID    orderId,      // UUID generated by producer — used as idempotency key
    String  customerId,
    String  product,
    int     quantity,
    double  price,        // unit price per item
    String  currency,
    Instant timestamp     // when the producer created the event
) {}
